/// Eight-point spacing tokens from the Servio Design System.
abstract final class AppSpacing {
  /// Micro spacing for tightly related elements.
  static const double xxs = 4;

  /// Base spacing for icon and label gaps.
  static const double xs = 8;

  /// Standard component padding.
  static const double sm = 16;

  /// Screen padding.
  static const double md = 24;

  /// Section spacing.
  static const double lg = 32;

  /// Large section spacing.
  static const double xl = 40;

  /// Major layout spacing.
  static const double xxl = 48;

  /// Maximum large-layout spacing.
  static const double xxxl = 64;
}
