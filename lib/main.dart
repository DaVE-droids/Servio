/// Bootstraps Firebase and launches the Servio application shell.
void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Clean web addresses (/coordinator/students/…) instead of /#/…, so links
  // can be shared and a page survives a browser refresh. The hosting
  // rewrite in firebase.json serves the app for every path. No effect on
  // mobile.
  usePathUrlStrategy();

  // Make the address bar follow pages opened on top of another (the bell,
  // the account menu, a student's detail page), so the browser's own Back
  // button closes them and the address can be copied or reloaded.
  // go_router warns against this because a pushed page's URL isn't always
  // reloadable — but every page Servio pushes carries its own identity in
  // the URL (/notifications, /coordinator/students/<id>), so each one
  // stands on its own.
  GoRouter.optionURLReflectsImperativeAPIs = true;

  _installErrorHandlers();

  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  runApp(const ProviderScope(child: ServioApp()));
}

/// Catches errors that would otherwise be lost, and replaces Flutter's grey
/// error box with a calm message in release builds.
///
/// When crash reporting is added (Firebase Crashlytics on Blaze, see
/// docs/STORE_RELEASE.md), report from the two handlers below.
void _installErrorHandlers() {
  FlutterError.onError = (details) {
    FlutterError.presentError(details);
    debugPrint('Flutter error: ${details.exceptionAsString()}');
  };
  PlatformDispatcher.instance.onError = (error, stack) {
    debugPrint('Uncaught error: $error\n$stack');
    return true;
  };
  if (kReleaseMode) {
    ErrorWidget.builder = (details) => const _BrokenWidgetNotice();
  }
}

/// Shown in place of a part of a screen that failed to build.
class _BrokenWidgetNotice extends StatelessWidget {
  const _BrokenWidgetNotice();

  @override
  Widget build(BuildContext context) {
    return const Directionality(
      textDirection: TextDirection.ltr,
      child: Padding(
        padding: EdgeInsets.all(16),
        child: Text(
          'Something on this screen couldn’t be shown. Go back and try again.',
          style: TextStyle(color: AppColors.textSecondary, fontSize: 13),
        ),
      ),
    );
  }
}
